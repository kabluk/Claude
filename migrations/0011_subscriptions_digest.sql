-- A3-CRON-DIGEST-EMAIL (D-137): один столбец, решающий архитектурный долг
-- «пара сканов для дельты не переживает cron-тик» (назван в notes
-- A3-CRON-RESCAN-DELTA и в TODO хвоста worker/lib/subscriptionCron.js).
--
-- ПРОБЛЕМА. Чтобы посчитать дельту, дайджесту нужны ДВА завершённых скана
-- одного url — предыдущий и новый. Но `last_scan_id` перезаписывается на новый
-- скан сразу при постановке ре-скана в очередь (subscriptionCron.js::
-- setLastScanId), а новый скан в этот момент ещё `running` (завершится в
-- консьюмере минутами позже). К тому времени, когда новый скан готов и письмо
-- можно строить, старый scan_id в строке подписки уже не хранится нигде.
--
-- РЕШЕНИЕ (вариант B из notes, но одной колонкой вместо двух). Вместо
-- `prev_scan_id`, который пришлось бы писать в enqueue-пути готового узла
-- RESCAN-DELTA (риск для уже закрытого кода), заводим `last_digest_scan_id` —
-- указатель на скан, ПО КОТОРЫЙ подписчику уже отправлен (или для которого уже
-- оценён) дайджест. Он делает ДВЕ работы разом:
--   * «предыдущий скан» для computeScanDelta — это последний скан, о котором мы
--     писали подписчику: дельта письма буквально значит «что изменилось с
--     прошлого письма», а не «между двумя соседними ре-сканами». Это устойчивее
--     к упавшему промежуточному ре-скану (сравниваем с последним, что человек
--     реально видел, а не с провалившимся сканом).
--   * маркер идемпотентности: пока `last_digest_scan_id == last_scan_id`,
--     дайджест по этому скану уже обработан и повторно НЕ шлётся. Без такого
--     маркера каждый ежедневный тик между двумя недельными ре-сканами слал бы
--     одно и то же письмо заново (до 6 дублей).
-- Обновляет эту колонку ТОЛЬКО дайджест-проход (runSubscriptionDigests), путь
-- постановки ре-скана (enqueueRescan) не трогается вовсе.
--
-- NULL — ни одного дайджеста ещё не оценивалось: первый завершённый ре-скан
-- заводит базовую линию (сравнивать не с чем, письмо не шлём), маркер
-- продвигается, письма нет. Логическая ссылка на scans.id БЕЗ FK — ровно как
-- last_scan_id/leads.scan_id: сканы удаляются по TTL (D-019), FK ронял бы
-- удаление или каскадом сносил подписку.
ALTER TABLE subscriptions ADD COLUMN last_digest_scan_id TEXT;
