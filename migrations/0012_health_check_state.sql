-- R-HEALTH-CRON (D-188): состояние ежедневного prod health-check'а
-- (worker/lib/healthcheck.js), нужное ровно для одной вещи — не слать
-- владельцу письмо каждую ночь, пока прод лежит на одной и той же поломке.
--
-- Один singleton-ряд (id=1, CHECK гарантирует, что второй никогда не
-- вставится) — состояние ГЛОБАЛЬНОЕ для всего прод-сайта, не по проверке и
-- не по подписчику, так что таблица «на одну подписку» (как subscriptions)
-- тут не подходит: это не список чего-то, а один флаг с историей.
--
-- D1, а не KV — выбор между двумя уже одобренными хранилищами узла
-- (RATE_LIMIT_KV/EXPLAIN_CACHE и accessatlas-scans D1). Есть 3 причины именно
-- за D1:
--   1. У этого состояния нет TTL — оно обязано пережить сколько угодно тиков
--      подряд, пока прод не поправят. Все существующие KV-биндинги в проекте
--      (ratelimit.js) устроены вокруг `expirationTtl` как основного паттерна;
--      health-состояние без TTL было бы исключением в модуле, который для
--      этого не создавался.
--   2. Переиспользовать `RATE_LIMIT_KV` под несвязанный смысл (не rate limit)
--      усложнило бы читаемость этого namespace для любого, кто по имени
--      биндинга ожидает найти там только счётчики окон.
--   3. Создание НОВОГО KV namespace — это новый инфраструктурный ресурс на
--      живом аккаунте владельца (`wrangler kv namespace create`), а D1
--      `accessatlas-scans` уже создана и одобрена (D-021); миграция поверх
--      неё не требует никакого нового ресурса — только код и `wrangler d1
--      migrations apply`, которое остаётся частью уже одобренного пайплайна.
--
-- status: 'ok' | 'down' — правда ПОСЛЕДНЕГО тика, перезаписывается каждый раз.
-- alerted_status: 'ok' | 'down' | NULL — статус, о котором владелец УЖЕ успешно
-- уведомлён письмом. Тот же приём, что `last_digest_scan_id` в 0011 (маркер
-- «уже сделано» ОТДЕЛЬНО от текущей истины): двигается ТОЛЬКО при успешной
-- отправке письма, поэтому упавшая отправка Resend не глотает алерт молча —
-- следующий тик увидит status='down' != alerted_status и попробует снова
-- (см. healthcheck.js::runHealthCheck). 'unknown' НЕ хранится как строка — до
-- первого тика строки просто нет и alerted_status тоже NULL, это чище, чем
-- третье строковое значение, которое пришлось бы держать в синхроне с кодом
-- в двух местах.
CREATE TABLE health_check_state (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  status TEXT NOT NULL,
  alerted_status TEXT,
  updated_at TEXT NOT NULL,
  last_failures_json TEXT,
  last_alert_sent_at TEXT
);
