// Канонический хост: 301 с `www.verscala.com` на голый `verscala.com`.
//
// ЗАЧЕМ. В индексе Google 2026-08-13 обнаружились обе версии сразу
// (`verscala.com/` И `www.verscala.com/methodology/` и т.д.) — оба хоста
// отдавали 200 без редиректа. `rel=canonical` на страницах уже указывал на
// apex и Google со временем склеил бы сигналы сам, но canonical — это
// ПОДСКАЗКА, а 301 — указание: он передаёт ссылочный вес однозначно, убирает
// дубли из индекса быстрее и не даёт внешним ссылкам на www расщеплять
// авторитет домена. Для сайта, который только начинает набирать индекс
// (157 страниц из 460 в sitemap), это дешёвая и разовая правка.
//
// ПОЧЕМУ ИМЕННО ЗДЕСЬ, а не `_redirects` и не Redirect Rule:
//   * `public/_redirects` (Cloudflare Pages) домены НЕ умеет — по документации
//     редиректы уровня домена явно не поддерживаются, матчинг только по пути;
//     проверено перед тем, как писать этот файл, не предположено.
//   * Cloudflare Redirect Rule (уровень зоны) — самый дешёвый по рантайму
//     вариант и остаётся лучшей альтернативой, НО требует токена с правом
//     Zone → Dynamic Redirect; у токена деплоя (DNS + Pages) его нет.
//     Если такой токен появится, эту миддлварь можно снять — тогда редирект
//     уедет на край сети и вовсе перестанет стоить инвокаций.
//   * Pages Functions матчатся ДО статических ассетов (тот же механизм, на
//     котором держится functions/report/[[path]].js, D-103) — значит www
//     перехватывается раньше, чем отдастся любая страница или ассет.
//
// ЦЕНА. Корневая миддлварь проходит через себя ВСЕ запросы проекта, включая
// статические ассеты. Поэтому тело обязано быть тривиальным: одна проверка
// хоста и немедленный next(). Никакой логики, никаких сетевых вызовов, ничего
// асинхронного на «обычном» пути — иначе каждая картинка на сайте начнёт
// платить за чужую работу.
export async function onRequest(context) {
  const url = new URL(context.request.url)

  // Точное сравнение, не `startsWith('www')`: сравнивать префиксом значит
  // однажды поймать легитимный хост вроде `www2.` или `wwwapi.`.
  if (url.hostname === 'www.verscala.com') {
    url.hostname = 'verscala.com'
    // 301, а не 302: редирект постоянный и должен кэшироваться и учитываться
    // поисковиком как перенос, иначе он не передаёт вес.
    // Путь, query и hash сохраняются целиком (url тот же объект) — иначе
    // внешняя ссылка на www.verscala.com/agencies/foo/ уводила бы человека
    // на главную вместо запрошенной страницы.
    return Response.redirect(url.toString(), 301)
  }

  return context.next()
}
